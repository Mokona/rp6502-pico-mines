# Collect all .bin in data_tile to make one big asset with all of them plus #define

import argparse
import sys
from pathlib import Path

def main():
    p = argparse.ArgumentParser(description="Collect tile binaries to make the atlas")
    p.add_argument("indir", type=Path, help="input directory")
    p.add_argument("outfile", type=Path, help="output directory")
    args = p.parse_args()

    full_data = b''
    file_count = 0
    header_text = '// Generated by collect_tiles.py\n\n'

    for input_file in sorted(args.indir.iterdir()):
        if input_file.is_file() and input_file.suffix == ".bin":
            print(f"Adding: {input_file}")
            full_data += input_file.read_bytes()

            define_name = str.upper(input_file.stem)
            header_text += f"#define {define_name} {file_count}\n"
            file_count += 1

    header_text += f"#define MAX_TILES {file_count}\n"

    print(f"Total: {len(full_data)} bytes, {file_count} files, average: {len(full_data) // file_count} bytes per file")

    args.outfile.parent.mkdir(exist_ok=True, parents=True)
    args.outfile.write_bytes(full_data)

    header_file_name = Path(args.outfile.parent).joinpath(args.outfile.stem + ".h")
    header_file = Path(header_file_name)

    header_file.write_text(header_text)

if __name__ == "__main__":
    main()